// PUBLIC_INTERFACE
function ScoreCard({ 
  quizScore, 
  contractRisk, 
  overallScore, 
  overallGrade, 
  showToast, 
  quizRisk, 
  contractFlags, 
  contractRecs, 
  summary, 
  recommendations 
}) {
  // Animate main score (on mount & score change).
  const [animatedScore, setAnimatedScore] = useState(0);
  React.useEffect(() => {
    let raf;
    const duration = 900;
    const start = 0;
    const end = overallScore;
    const update = (timestamp, startTime) => {
      const elapsed = Math.min(duration, timestamp - startTime);
      const value = Math.round(start + (end - start) * (elapsed / duration));
      setAnimatedScore(value);
      if (elapsed < duration) {
        raf = requestAnimationFrame(ts => update(ts, startTime));
      } else {
        setAnimatedScore(end);
      }
    };
    const startTime = performance.now();
    raf = requestAnimationFrame(ts => update(ts, startTime));
    return () => raf && cancelAnimationFrame(raf);
  }, [overallScore]);

  // Create a simple .txt report summarizing the dashboard results
  function getTextReport() {
    // Quiz section
    let text = '';
    text += "==== CyberLegal Insight Report ====\n";
    text += `Quiz Score: ${quizScore}/100 (${quizRisk || "N/A"})\n`;
    text += `Contract Safety Score: ${contractRisk}/100\n`;
    text += `Overall Risk: ${summary?.riskScore || "-"} /100 (${summary?.riskGrade || "-"})\n\n`;
    text += "Key Contract Findings:\n";
    if (Array.isArray(contractFlags) && contractFlags.length) {
      contractFlags.forEach((flag, idx) => {
        text += `  - ${flag}\n`;
      });
    } else {
      text += "  None detected.\n";
    }
    text += "\nSystem Recommendations:\n";
    if (Array.isArray(recommendations)) {
      recommendations.forEach((rec, idx) => {
        text += `  - ${rec}\n`;
      });
    }
    if (Array.isArray(contractRecs) && contractRecs.length) {
      text += "\nLegal Tips:\n";
      contractRecs.forEach((rec, i) => {
        text += `  - ${rec}\n`;
      });
    }
    return text + "\nGenerated by CyberLegal Insight Hub (https://cyberlegal.kavia.ai)\n";
  }

  // PUBLIC_INTERFACE
  // Download button handler: generate report as a .txt and trigger browser download
  const handleDownload = () => {
    try {
      const text = getTextReport();
      const blob = new Blob([text], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = "cyberlegal-insight-report.txt";
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(url), 2222);
      showToast("Report downloaded!");
    } catch (e) {
      showToast("Failed to download report.");
    }
  };

  // PUBLIC_INTERFACE
  // Share handler: build a summary string, copy to clipboard, show toast
  const handleShare = async () => {
    const summaryStr = [
      "CyberLegal Insight Brief:",
      `Quiz: ${quizScore}/100 (${quizRisk || "-"})`,
      `Contract: ${contractRisk}/100`,
      `Overall: ${summary?.riskScore || "-"} /100 (${summary?.riskGrade || "-"})`,
      "Key Recommendation:",
      recommendations && recommendations[0] ? `- ${recommendations[0]}` : "",
      "(Full report generated at https://cyberlegal.kavia.ai)"
    ].filter(Boolean).join('\n');
    try {
      if (navigator.clipboard) {
        await navigator.clipboard.writeText(summaryStr);
        showToast("Summary copied to clipboard!");
      } else {
        // fallback approach (not recommended, but basic legacy support)
        const t = document.createElement("textarea");
        t.value = summaryStr;
        document.body.appendChild(t);
        t.select();
        document.execCommand("copy");
        document.body.removeChild(t);
        showToast("Summary copied!");
      }
    } catch (e) {
      showToast("Copy failed.");
    }
  };

  // Email can remain a stub or be omitted here as not required in the task
  const handleEmail = () => {
    showToast("Email report: Feature coming soon!");
  };

  return (
    <div className="glass-card neumorph-shadow dashboard-scorecard">
      <div className="dashboard-score-smalls">
        <div>
          <span className="score-label">Quiz</span>
          <span className="score-num">{quizScore}</span>
        </div>
        <div>
          <span className="score-label">Contract</span>
          <span className="score-num">{contractRisk}</span>
        </div>
      </div>
      <div className="score-main-anim" aria-label={`Overall Score: ${animatedScore}`}>
        <span className="score-big">{animatedScore}</span>
        <span className="score-grade">/100</span>
        <span className="score-tag">{overallGrade}</span>
      </div>
      <div className="score-cta-btns">
        <button className="dashboard-action-btn" title="Download report as TXT" onClick={handleDownload}>
          <span role="img" aria-label="download">⬇️</span>
        </button>
        <button className="dashboard-action-btn" title="Email report" onClick={handleEmail}>
          <span role="img" aria-label="email">✉️</span>
        </button>
        <button className="dashboard-action-btn" title="Share dashboard" onClick={handleShare}>
          <span role="img" aria-label="share">🔗</span>
        </button>
      </div>
    </div>
  );
}

