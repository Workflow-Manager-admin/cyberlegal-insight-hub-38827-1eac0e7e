/** Simple Toast component for demo CTA feedback */
function DemoToast({ message, onClose }) {
  React.useEffect(() => {
    if (!message) return;
    const timer = setTimeout(onClose, 2000);
    return () => clearTimeout(timer);
  }, [message]);
  if (!message) return null;
  return (
    <div
      className="dashboard-toast"
      style={{
        position: "fixed",
        bottom: 34,
        left: "50%",
        transform: "translateX(-50%)",
        background:
          "linear-gradient(92deg, var(--primary,#2563eb) 70%, var(--accent,#fbbf24) 130%)",
        color: "#fff",
        fontWeight: 600,
        fontSize: 17,
        borderRadius: 12,
        boxShadow: "0 2.5px 24px #2563eb33, 0 1.5px 5px #fff2",
        padding: "11px 34px",
        zIndex: 3333,
        opacity: 0.98,
        pointerEvents: "none",
      }}
      role="status"
      aria-live="polite"
    >
      {message}
    </div>
  );
}
